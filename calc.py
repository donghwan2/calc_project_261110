def sum(a, b): # 더하기 주석 입니다
    return a + b


def sub(a, b): 
    return a - b

# 곱하기 주석 추가
def mul(a, b):
    return a * b

# 나누기 입니다
def div(a, b):
    if b == 0:
        return 0
    else:
        return a / b

# 제곱 입니다
def square(a):
    return a**2


